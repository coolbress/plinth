#!/usr/bin/env bash
# An edit to a pull request's title or description re-runs only the checks
# that read them (#1133). GitHub keeps each workflow's latest run of a check
# name and requires all of them to pass, so every name an edit re-runs is
# reported by one workflow (measured on a test pull request for #1133):
#
# - ci.yml runs on a push and on opening, and never on `edited`; its `ci` job
#   calls plinth-ci.yml, which has no `docs` or `release-gate` job.
# - ci-text.yml runs on those and on `edited`, queued per pull request and
#   head (cancel-in-progress false), so an edit's run starts after the push's
#   and cancels nothing. Its `ci` job calls plinth-ci-text.yml, which has
#   exactly `release-gate` and `docs`; every `ci / <job>` plinth's ruleset
#   requires is a job of one of the two files, never of both.
# - Its canary jobs call python-ci-text.yml, which is python-ci.yml's
#   `pr-title` and `diff-size` jobs and its inputs, generated by this file;
#   each one's name, grant and inputs are its ci.yml counterpart's.
#
#   tests/ci-text.sh           check
#   tests/ci-text.sh --write   regenerate python-ci-text.yml from python-ci.yml
set -uo pipefail
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
wf="$root/.github/workflows"
python3 -c 'import sys; sys.exit(sys.version_info < (3, 11))' \
  || { echo "  FAIL  needs python3 3.11 or later, as the runner has; got $(python3 --version 2>&1)"; exit 1; }
work="$(mktemp -d "${TMPDIR:-/tmp}/ci-text.XXXXXX")" || { echo "  FAIL  mktemp"; exit 1; }
trap 'rm -rf "$work"' EXIT
pass=0; fail=0
ok()  { pass=$((pass+1)); printf '  PASS  %s\n' "$1"; }
bad() { fail=$((fail+1)); printf '  FAIL  %s\n' "$1"; [ -n "${2:-}" ] && printf '%s\n' "$2" | sed 's/^/        | /'; }

cat >"$work/lib.py" <<'PY'
import re

def lines(path):
    return open(path, encoding="utf-8").read().split("\n")

def job_starts(L):
    return [i for i, l in enumerate(L) if re.match(r"^  [A-Za-z0-9_-]+:\s*$", l)]

def job(L, name):
    """The job's lines, with the comment lines right above its key."""
    starts = job_starts(L)
    s = L.index(f"  {name}:")
    nxt = next((i for i in starts if i > s), len(L))
    # The next job's own comment block is not this job's.
    e = nxt
    while e - 1 > s and (L[e - 1].startswith("  #") or not L[e - 1].strip()):
        e -= 1
    b = s
    while b - 1 >= 0 and L[b - 1].startswith("  #"):
        b -= 1
    return L[b:e]

def on_block(L):
    s = L.index("on:")
    e = next(i for i in range(s + 1, len(L)) if re.match(r"^[A-Za-z#]", L[i]))
    while not L[e - 1].strip():
        e -= 1
    return L[s:e]

HEADER = """# Rule: a caller's Actions allowlist covers this file; a third-party action stops every consumer's checks (#867).
name: python-ci-text
# GENERATED from python-ci.yml by `tests/ci-text.sh --write`; do not edit.
# python-ci.yml's `pr-title` and `diff-size` jobs and its inputs, copied, so
# that plinth's own ci-text.yml re-runs its canaries' two checks that read the
# pull request's title and description on an edit, without the code jobs
# (#1133). Consumers call python-ci.yml, never this file. tests/ci-text.sh
# fails when this copy and python-ci.yml differ."""

def generate(src):
    L = lines(src)
    out = HEADER.split("\n") + [""] + on_block(L) + ["", "permissions:", "  contents: read", "", "jobs:"]
    out += job(L, "pr-title") + [""] + job(L, "diff-size")
    while not out[-1].strip():
        out.pop()
    return "\n".join(out) + "\n"
PY

if [ "${1:-}" = --write ]; then
  python3 - "$work" "$wf/python-ci.yml" "$wf/python-ci-text.yml" <<'PY' || exit 1
import sys; sys.path.insert(0, sys.argv[1]); import lib
open(sys.argv[3], "w", encoding="utf-8").write(lib.generate(sys.argv[2]))
PY
  echo "wrote .github/workflows/python-ci-text.yml"; exit 0
fi

# 1. The copy is python-ci.yml's, byte for byte.
python3 - "$work" "$wf/python-ci.yml" >"$work/want.yml" <<'PY'
import sys; sys.path.insert(0, sys.argv[1]); import lib
sys.stdout.write(lib.generate(sys.argv[2]))
PY
if [ ! -f "$wf/python-ci-text.yml" ]; then
  bad "no .github/workflows/python-ci-text.yml; run tests/ci-text.sh --write"
elif d="$(diff "$work/want.yml" "$wf/python-ci-text.yml")"; then
  ok "python-ci-text.yml is python-ci.yml's pr-title and diff-size jobs and inputs"
else
  bad "python-ci-text.yml differs from python-ci.yml's jobs; run tests/ci-text.sh --write" "$(head -20 <<<"$d")"
fi

# 2. The wiring of ci.yml, ci-text.yml and the two reusable files.
# A check that stops with an error fails the test, whatever it printed first.
wiring_rc=0
python3 - "$work" "$wf" "$root/scripts/check-ruleset.sh" >"$work/out" 2>"$work/err" <<'PY' || wiring_rc=$?
import json, re, sys
sys.path.insert(0, sys.argv[1]); import lib
wf = sys.argv[2]
ci, text = lib.lines(f"{wf}/ci.yml"), lib.lines(f"{wf}/ci-text.yml")
plinth, plinth_text = lib.lines(f"{wf}/plinth-ci.yml"), lib.lines(f"{wf}/plinth-ci-text.yml")
def say(ok, msg): print(("PASS " if ok else "FAIL ") + msg)
def types(L):
    t = next((l for l in L if l.strip().startswith("types:")), "")
    return [x.strip() for x in t.split("[", 1)[-1].rstrip("]").split(",")] if "[" in t else []
def jobs(L):
    return [L[i].strip()[:-1] for i in lib.job_starts(L) if i > L.index("jobs:")]

say("edited" not in types(ci) and types(ci) == ["opened", "synchronize", "reopened"],
    f"ci.yml runs on opened, synchronize and reopened, not on an edit (types: {types(ci)})")
say(types(text) == ["opened", "synchronize", "reopened", "edited"],
    f"ci-text.yml runs on those and on an edit (types: {types(text)})")
conc = "\n".join(l for l in text if l.startswith("concurrency:") or l.startswith("  group:") or l.startswith("  cancel-in-progress:"))
say("cancel-in-progress: false" in conc and "head.sha" in conc and "pull_request.number" in conc,
    "ci-text.yml queues its runs per pull request and head, and cancels none")
say(any(l.strip() == "uses: ./.github/workflows/plinth-ci.yml" for l in lib.job(ci, "ci")),
    "ci.yml's ci job calls plinth-ci.yml")
say(any(l.strip() == "uses: ./.github/workflows/plinth-ci-text.yml" for l in lib.job(text, "ci")),
    "ci-text.yml's ci job calls plinth-ci-text.yml")
say(sorted(jobs(plinth_text)) == ["docs", "release-gate"],
    f"plinth-ci-text.yml has exactly the docs and release-gate jobs ({jobs(plinth_text)})")
own = json.loads(re.search(r"^own_checks='(.*)'$", open(sys.argv[3]).read(), re.M).group(1))
for c in [c[len("ci / "):] for c in own if c.startswith("ci / ")]:
    where = [n for n, L in (("plinth-ci.yml", plinth), ("plinth-ci-text.yml", plinth_text)) if c in jobs(L)]
    say(len(where) == 1, f"ci / {c}, required on plinth, is a job of one workflow: {where}")
for c in ("canary", "canary-web", "canary-template"):
    a = [l for l in lib.job(ci, c) if not l.strip().startswith("#")]
    b = [l for l in lib.job(text, c) if not l.strip().startswith("#")]
    a = [l.replace("python-ci.yml", "python-ci-text.yml") for l in a]
    say(a == b, f"ci-text.yml's {c} has ci.yml's name, grant and inputs, calling python-ci-text.yml")
extra = sorted(set(jobs(text)) - {"ci", "canary", "canary-web", "canary-template"})
say(not extra, f"ci-text.yml has no other job ({extra})")
PY
while read -r verdict msg; do
  [ "$verdict" = PASS ] && ok "$msg" || bad "$msg"
done <"$work/out"
[ -s "$work/out" ] || bad "the wiring checks printed nothing"
[ "$wiring_rc" = 0 ] || bad "the wiring checks stopped with an error (exit $wiring_rc), so the ones after it did not run" "$(tail -5 "$work/err")"

echo "ci-text: $pass passed, $fail failed"
[ "$fail" = 0 ]
